"""Visualization and Result Aggregation Module.

Generates research-grade figures and tables from experiment outputs:
1. Stacked error breakdown plots across severities (TP, Miss, Bkg, Loc, Cls, Dupe).
2. Metric trajectories across degradation severities (mAP, Recall, Miss Rate).
3. Cross-model comparison plots (comparing failure modes across detector architectures).
4. Paper-ready LaTeX, Markdown, and CSV summary tables.
"""

from typing import List, Dict, Any, Optional, Union
from pathlib import Path
import json
import argparse
import pandas as pd

import matplotlib
matplotlib.use("Agg")  # Headless rendering for reproducibility and server environments
import matplotlib.pyplot as plt


# Distinct, publication-standard color palette for error categories
ERROR_PALETTE = {
    "True Positive": "#2ca02c",       # Green
    "Missed (FN)": "#d62728",         # Red
    "Background (FP)": "#9467bd",     # Purple
    "Localization Err": "#bcbd22",    # Olive / Yellow
    "Classification Err": "#1f77b4",  # Blue
    "Duplicate Det": "#7f7f7f",       # Gray
}


def load_experiment_summary(file_path: Union[str, Path]) -> Dict[str, Any]:
    """Loads an experiment summary JSON file generated by pipeline.py."""
    with open(file_path, "r") as f:
        return json.load(f)


def plot_error_breakdown(
    experiment_data: Dict[str, Any],
    output_path: Union[str, Path],
    as_percentage: bool = True,
) -> Path:
    """
    Plots a stacked bar chart illustrating the error composition from Clean baseline
    through Severities 1 to 5.

    Args:
        experiment_data: Output dictionary from pipeline.run_degradation_experiment.
        output_path: Destination path for saved PNG figure.
        as_percentage: If True, normalizes each condition to 100%.

    Returns:
        Path to the saved image file.
    """
    model = experiment_data.get("model", "Detector")
    degradation = experiment_data.get("degradation", "Degradation")
    clean = experiment_data["clean_baseline"]
    severities_data = experiment_data.get("severities_data", {})

    labels = ["Clean"] + [f"Sev {s}" for s in sorted([int(k) for k in severities_data.keys()])]
    conditions = [clean] + [severities_data[str(s)] if str(s) in severities_data else severities_data[int(s)]
                            for s in sorted([int(k) for k in severities_data.keys()])]

    categories = [
        "True Positive",
        "Missed (FN)",
        "Background (FP)",
        "Localization Err",
        "Classification Err",
        "Duplicate Det",
    ]

    data: Dict[str, List[float]] = {cat: [] for cat in categories}

    for cond in conditions:
        raw = cond["raw_counts"]
        data["True Positive"].append(raw.get("tp", 0))
        data["Missed (FN)"].append(raw.get("miss", 0))
        data["Background (FP)"].append(raw.get("bkg", 0))
        data["Localization Err"].append(raw.get("loc", 0))
        data["Classification Err"].append(raw.get("cls", 0) + raw.get("cls_loc", 0))
        data["Duplicate Det"].append(raw.get("dupe", 0))

    df = pd.DataFrame(data, index=labels)

    if as_percentage:
        # Normalize each row to sum to 100%
        row_totals = df.sum(axis=1)
        row_totals[row_totals == 0] = 1.0
        df = df.div(row_totals, axis=0) * 100.0
        y_label = "Error Budget Composition (%)"
    else:
        y_label = "Object & Detection Count"

    fig, ax = plt.subplots(figsize=(8, 5), dpi=300)
    bottom = pd.Series([0.0] * len(labels), index=labels)

    for cat in categories:
        ax.bar(
            labels,
            df[cat],
            bottom=bottom,
            label=cat,
            color=ERROR_PALETTE[cat],
            edgecolor="white",
            linewidth=0.8,
            width=0.55,
        )
        bottom += df[cat]

    ax.set_ylabel(y_label, fontsize=12, fontweight="medium")
    ax.set_title(
        f"Diagnostic Error Decomposition under {degradation.replace('_', ' ').title()}\nModel: {model}",
        fontsize=13,
        fontweight="bold",
        pad=12,
    )
    ax.legend(loc="upper left", bbox_to_anchor=(1.02, 1.0), frameon=True, fontsize=10)
    ax.set_ylim(0, 100 if as_percentage else None)
    ax.grid(axis="y", linestyle="--", alpha=0.4)

    plt.tight_layout()
    out = Path(output_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(out, bbox_inches="tight")
    plt.close(fig)

    return out


def plot_metric_trajectories(
    experiment_data: Dict[str, Any],
    output_path: Union[str, Path],
) -> Path:
    """
    Plots metric trajectories (Recall, Miss Rate, mAP) across degradation severities.
    """
    model = experiment_data.get("model", "Detector")
    degradation = experiment_data.get("degradation", "Degradation")
    severities_data = experiment_data.get("severities_data", {})

    sorted_sevs = sorted([int(k) for k in severities_data.keys()])
    x_vals = [0] + sorted_sevs
    x_labels = ["Clean"] + [f"Sev {s}" for s in sorted_sevs]

    clean_summary = experiment_data["clean_baseline"]["summary"]
    clean_map = experiment_data["clean_baseline"].get("coco_metrics")

    recalls = [clean_summary["recall"]]
    miss_rates = [clean_summary["miss_rate"]]
    maps = [clean_map["mAP_50_95"] if clean_map else None]

    for s in sorted_sevs:
        s_entry = severities_data[str(s)] if str(s) in severities_data else severities_data[s]
        s_sum = s_entry["summary"]
        s_map = s_entry.get("coco_metrics")

        recalls.append(s_sum["recall"])
        miss_rates.append(s_sum["miss_rate"])
        maps.append(s_map["mAP_50_95"] if s_map else None)

    fig, ax1 = plt.subplots(figsize=(7, 4.5), dpi=300)

    # Plot Recall and Miss Rate on primary axis
    ax1.plot(x_vals, [r * 100 for r in recalls], "o-", color="#2ca02c", label="Recall (%)", linewidth=2)
    ax1.plot(x_vals, [m * 100 for m in miss_rates], "s--", color="#d62728", label="Miss Rate (%)", linewidth=2)

    # Plot mAP if available
    has_map = any(m is not None for m in maps)
    if has_map:
        clean_maps = [m * 100 if m is not None else 0.0 for m in maps]
        ax1.plot(x_vals, clean_maps, "^-.", color="#1f77b4", label="mAP@50:95 (%)", linewidth=2)

    ax1.set_xlabel("Degradation Severity", fontsize=11, fontweight="medium")
    ax1.set_ylabel("Metric Score (%)", fontsize=11, fontweight="medium")
    ax1.set_xticks(x_vals)
    ax1.set_xticklabels(x_labels)
    ax1.set_ylim(-2, 102)
    ax1.grid(True, linestyle=":", alpha=0.5)

    ax1.set_title(
        f"Performance Trajectory under {degradation.replace('_', ' ').title()} ({model})",
        fontsize=12,
        fontweight="bold",
        pad=10,
    )
    ax1.legend(loc="best", frameon=True)

    plt.tight_layout()
    out = Path(output_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(out, bbox_inches="tight")
    plt.close(fig)

    return out


def plot_model_comparison(
    experiment_files: List[Union[str, Path]],
    output_path: Union[str, Path],
    metric: str = "delta_miss_rate",
) -> Path:
    """
    Compares how different detector families respond across severities.
    E.g. compares delta_miss_rate or background FP between YOLO11, Faster R-CNN, and RT-DETR.
    """
    fig, ax = plt.subplots(figsize=(8, 4.8), dpi=300)
    markers = ["o-", "s--", "^-.", "d:"]

    deg_name = None

    for idx, fpath in enumerate(experiment_files):
        data = load_experiment_summary(fpath)
        model = data.get("model", f"Model {idx+1}")
        deg_name = data.get("degradation", "Degradation")
        comp_table = data.get("comparison_table", [])

        if not comp_table:
            continue

        sevs = [row["severity"] for row in comp_table]
        vals = [row.get(metric, 0.0) for row in comp_table]

        # Convert rate fractions to percentages if metric is a rate
        if "rate" in metric:
            vals = [v * 100 for v in vals]

        marker = markers[idx % len(markers)]
        ax.plot(sevs, vals, marker, label=model, linewidth=2, markersize=7)

    y_label_str = metric.replace("_", " ").title()
    if "rate" in metric:
        y_label_str += " (%)"

    ax.set_xlabel("Severity Level", fontsize=11, fontweight="medium")
    ax.set_ylabel(y_label_str, fontsize=11, fontweight="medium")
    title_deg = deg_name.replace("_", " ").title() if deg_name else ""
    ax.set_title(f"Cross-Detector Failure Comparison: {title_deg}", fontsize=12, fontweight="bold", pad=10)
    ax.set_xticks([1, 2, 3, 4, 5])
    ax.grid(True, linestyle=":", alpha=0.5)
    ax.legend(loc="best", frameon=True)

    plt.tight_layout()
    out = Path(output_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(out, bbox_inches="tight")
    plt.close(fig)

    return out


def _format_markdown_table(df: pd.DataFrame) -> str:
    """Formats a pandas DataFrame as a Markdown table without requiring third-party dependencies."""
    cols = [str(c) for c in df.columns]
    header = "| " + " | ".join(cols) + " |"
    separator = "| " + " | ".join(["---"] * len(cols)) + " |"
    rows = []
    for _, row in df.iterrows():
        row_str = "| " + " | ".join(str(row[c]) if pd.notna(row[c]) else "" for c in df.columns) + " |"
        rows.append(row_str)
    return "\n".join([header, separator] + rows) + "\n"


def export_summary_table(
    experiment_data: Dict[str, Any],
    output_prefix: Union[str, Path],
) -> Dict[str, Path]:
    """
    Exports clean comparison tables in CSV, Markdown, and LaTeX formats.
    """
    comp_table = experiment_data.get("comparison_table", [])
    if not comp_table:
        return {}

    df = pd.DataFrame(comp_table)

    # Rename columns for thesis-quality presentation
    column_mapping = {
        "severity": "Severity",
        "mAP_50_95": "mAP",
        "recall": "Recall",
        "miss_rate": "Miss Rate",
        "delta_miss_rate": "Δ Miss Rate",
        "background_fp": "Bkg FP",
        "localization_err": "Loc Err",
        "classification_err": "Cls Err",
        "duplicate_det": "Dupe",
        "primary_diagnosis": "Primary Failure Mechanism",
    }
    df = df.rename(columns=column_mapping)

    prefix = Path(output_prefix)
    prefix.parent.mkdir(parents=True, exist_ok=True)

    csv_path = prefix.with_suffix(".csv")
    md_path = prefix.with_suffix(".md")
    tex_path = prefix.with_suffix(".tex")

    df.to_csv(csv_path, index=False)

    with open(md_path, "w") as f:
        f.write(_format_markdown_table(df))

    with open(tex_path, "w") as f:
        f.write(df.to_latex(index=False, float_format="%.3f"))

    return {"csv": csv_path, "md": md_path, "tex": tex_path}


def main():
    parser = argparse.ArgumentParser(description="Generate Visualizations and Summary Tables")
    parser.add_argument("--input", help="Path to single experiment summary JSON")
    parser.add_argument("--inputs", nargs="+", help="Paths to multiple experiment summaries for model comparison")
    parser.add_argument("--out-dir", default="figures", help="Directory to save figures and tables")
    parser.add_argument("--comparison-metric", default="delta_miss_rate", help="Metric to compare across models")

    args = parser.parse_args()
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    if args.input:
        data = load_experiment_summary(args.input)
        model = data.get("model", "detector")
        deg = data.get("degradation", "degradation")

        p_breakdown = out_dir / f"{model}_{deg}_error_breakdown.png"
        plot_error_breakdown(data, p_breakdown)
        print(f"Saved: {p_breakdown}")

        p_traj = out_dir / f"{model}_{deg}_trajectories.png"
        plot_metric_trajectories(data, p_traj)
        print(f"Saved: {p_traj}")

        tbl_prefix = out_dir / f"{model}_{deg}_table"
        tbls = export_summary_table(data, tbl_prefix)
        print(f"Saved tables: {tbls}")

    if args.inputs and len(args.inputs) > 1:
        p_comp = out_dir / f"model_comparison_{args.comparison_metric}.png"
        plot_model_comparison(args.inputs, p_comp, metric=args.comparison_metric)
        print(f"Saved cross-model comparison: {p_comp}")


if __name__ == "__main__":
    main()
